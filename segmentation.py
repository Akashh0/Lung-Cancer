class ConvBlock(nn.Module):
    """
    A single convolutional block for V-Net, including convolution, PReLU activation, and dropout.
    """
    def __init__(self, in_channels, out_channels, num_convs=1):
        super(ConvBlock, self).__init__()
        layers = []
        for i in range(num_convs):
            layers.append(nn.Conv3d(in_channels if i == 0 else out_channels, out_channels, kernel_size=5, padding=2))
            layers.append(nn.PReLU(out_channels))
        self.conv_block = nn.Sequential(*layers)

    def forward(self, x):
        return self.conv_block(x)

class VNet(nn.Module):
    def __init__(self, in_channels=1, out_channels=1, num_features=16):
        super(VNet, self).__init__()

        # Contracting Path (Encoder)
        self.down_conv1 = ConvBlock(in_channels, num_features, num_convs=1)
        self.down_pool1 = nn.Conv3d(num_features, num_features * 2, kernel_size=2, stride=2)

        self.down_conv2 = ConvBlock(num_features * 2, num_features * 2, num_convs=2)
        self.down_pool2 = nn.Conv3d(num_features * 2, num_features * 4, kernel_size=2, stride=2)

        self.down_conv3 = ConvBlock(num_features * 4, num_features * 4, num_convs=3)
        self.down_pool3 = nn.Conv3d(num_features * 4, num_features * 8, kernel_size=2, stride=2)

        self.down_conv4 = ConvBlock(num_features * 8, num_features * 8, num_convs=3)
        self.down_pool4 = nn.Conv3d(num_features * 8, num_features * 16, kernel_size=2, stride=2)

        self.bottom_conv = ConvBlock(num_features * 16, num_features * 16, num_convs=3)

        # Expanding Path (Decoder)
        self.up_deconv4 = nn.ConvTranspose3d(num_features * 16, num_features * 8, kernel_size=2, stride=2)
        self.up_conv4 = ConvBlock(num_features * 16, num_features * 8, num_convs=3)

        self.up_deconv3 = nn.ConvTranspose3d(num_features * 8, num_features * 4, kernel_size=2, stride=2)
        self.up_conv3 = ConvBlock(num_features * 8, num_features * 4, num_convs=3)

        self.up_deconv2 = nn.ConvTranspose3d(num_features * 4, num_features * 2, kernel_size=2, stride=2)
        self.up_conv2 = ConvBlock(num_features * 4, num_features * 2, num_convs=2)

        self.up_deconv1 = nn.ConvTranspose3d(num_features * 2, num_features, kernel_size=2, stride=2)
        self.up_conv1 = ConvBlock(num_features * 2, num_features, num_convs=1)

        # Output layer
        self.final_conv = nn.Conv3d(num_features, out_channels, kernel_size=1)

    def forward(self, x):
        # Contracting Path
        x1 = self.down_conv1(x)
        p1 = self.down_pool1(x1)

        x2 = self.down_conv2(p1)
        p2 = self.down_pool2(x2)

        x3 = self.down_conv3(p2)
        p3 = self.down_pool3(x3)

        x4 = self.down_conv4(p3)
        p4 = self.down_pool4(x4)

        x_bottom = self.bottom_conv(p4)

        # Expanding Path
        u4 = self.up_deconv4(x_bottom)
        cat4 = torch.cat([u4, x4], dim=1)
        u4 = self.up_conv4(cat4)

        u3 = self.up_deconv3(u4)
        cat3 = torch.cat([u3, x3], dim=1)
        u3 = self.up_conv3(cat3)

        u2 = self.up_deconv2(u3)
        cat2 = torch.cat([u2, x2], dim=1)
        u2 = self.up_conv2(cat2)

        u1 = self.up_deconv1(u2)
        cat1 = torch.cat([u1, x1], dim=1)
        u1 = self.up_conv1(cat1)

        return self.final_conv(u1)

