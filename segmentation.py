def passthrough_block(in_channels, out_channels, kernel_size, stride, padding):
    return nn.Sequential(
        nn.Conv3d(in_channels, out_channels, kernel_size=kernel_size, stride=stride, padding=padding, bias=False),
        nn.BatchNorm3d(out_channels)
    )

class ResidualBlock(nn.Module):
    def __init__(self, in_channels, out_channels):
        super(ResidualBlock, self).__init__()
        self.conv_block = nn.Sequential(
            nn.Conv3d(in_channels, out_channels, kernel_size=5, padding=2, bias=False),
            nn.BatchNorm3d(out_channels),
            nn.ReLU(inplace=True),
            nn.Conv3d(out_channels, out_channels, kernel_size=5, padding=2, bias=False),
            nn.BatchNorm3d(out_channels)
        )
        self.relu = nn.ReLU(inplace=True)
        self.passthrough = passthrough_block(in_channels, out_channels, kernel_size=1, stride=1, padding=0) if in_channels != out_channels else None

    def forward(self, x):
        residual = self.passthrough(x) if self.passthrough else x
        return self.relu(self.conv_block(x) + residual)

class VNet(nn.Module):
    def __init__(self, in_channels=1, out_channels=1):
        super(VNet, self).__init__()
        self.down_conv1 = ResidualBlock(in_channels, 16)
        self.down_pool1 = passthrough_block(16, 32, kernel_size=2, stride=2, padding=0)

        self.down_conv2 = ResidualBlock(32, 32)
        self.down_pool2 = passthrough_block(32, 64, kernel_size=2, stride=2, padding=0)

        self.down_conv3 = ResidualBlock(64, 64)
        self.down_pool3 = passthrough_block(64, 128, kernel_size=2, stride=2, padding=0)

        self.down_conv4 = ResidualBlock(128, 128)
        self.down_pool4 = passthrough_block(128, 256, kernel_size=2, stride=2, padding=0)

        self.bottleneck = ResidualBlock(256, 256)

        self.up_deconv4 = nn.ConvTranspose3d(256, 128, kernel_size=2, stride=2)
        self.up_conv4 = ResidualBlock(256, 128)

        self.up_deconv3 = nn.ConvTranspose3d(128, 64, kernel_size=2, stride=2)
        self.up_conv3 = ResidualBlock(128, 64)

        self.up_deconv2 = nn.ConvTranspose3d(64, 32, kernel_size=2, stride=2)
        self.up_conv2 = ResidualBlock(64, 32)

        self.up_deconv1 = nn.ConvTranspose3d(32, 16, kernel_size=2, stride=2)
        self.up_conv1 = ResidualBlock(32, 16)

        self.final_conv = nn.Conv3d(16, out_channels, kernel_size=1)

    def forward(self, x):
        d1 = self.down_conv1(x)
        d2 = self.down_pool1(d1); d2 = self.down_conv2(d2)
        d3 = self.down_pool2(d2); d3 = self.down_conv3(d3)
        d4 = self.down_pool3(d3); d4 = self.down_conv4(d4)

        bottleneck_out = self.down_pool4(d4)
        bottleneck_out = self.bottleneck(bottleneck_out)

        u4 = self.up_deconv4(bottleneck_out); u4 = torch.cat((u4, d4), dim=1); u4 = self.up_conv4(u4)
        u3 = self.up_deconv3(u4); u3 = torch.cat((u3, d3), dim=1); u3 = self.up_conv3(u3)
        u2 = self.up_deconv2(u3); u2 = torch.cat((u2, d2), dim=1); u2 = self.up_conv2(u2)
        u1 = self.up_deconv1(u2); u1 = torch.cat((u1, d1), dim=1); u1 = self.up_conv1(u1)

        out = self.final_conv(u1)
        return out

