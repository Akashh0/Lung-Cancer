def test_and_visualize_combined(model_path, test_scan_path, test_mask_path, patch_size=(96, 96, 96)):
    DEVICE = "cuda" if torch.cuda.is_available() else "cpu"
    print(f"Using device: {DEVICE}")

    # --- Load the Model ---
    model = VNet().to(DEVICE)
    model.load_state_dict(torch.load(model_path, map_location=DEVICE))
    model.eval()
    print(f"✅ Model loaded successfully from {model_path}")

    # --- Load Test Data ---
    try:
        scan = np.load(test_scan_path)
        gt_mask = np.load(test_mask_path)
    except FileNotFoundError:
        print(f"!!! Error: Could not find one or both of the files. Please check your paths.")
        return

    # Extract a fixed patch
    depth, height, width = scan.shape
    pd, ph, pw = patch_size
    z, y, x = (depth - pd) // 2, (height - ph) // 2, (width - pw) // 2
    scan_patch = scan[z:z+pd, y:y+ph, x:x+pw]
    gt_mask_patch = gt_mask[z:z+pd, y:y+ph, x:x+pw]

    # Convert to tensor
    test_scan_tensor = torch.from_numpy(scan_patch).unsqueeze(0).unsqueeze(0).float().to(DEVICE)

    # --- Make Prediction ---
    with torch.no_grad():
        prediction_logits = model(test_scan_tensor)
        prediction_probs = torch.sigmoid(prediction_logits)
        predicted_mask = (prediction_probs > 0.5).float()

    # Get 2D slices for visualization
    slice_index = patch_size[0] // 2
    scan_slice = scan_patch[slice_index, :, :]
    gt_mask_slice = gt_mask_patch[slice_index, :, :]
    pred_mask_slice = predicted_mask.squeeze().cpu().numpy()[slice_index, :, :]

    # --- Visualization ---
    fig, axes = plt.subplots(1, 3, figsize=(18, 6))

    # Plot 1: Segmented Lung Nodule (Ground Truth)
    axes[0].imshow(gt_mask_slice, cmap='viridis')
    axes[0].set_title('Ground Truth Nodule', fontsize=16)
    axes[0].axis('off')

    # Plot 2: Predicted Nodule
    axes[1].imshow(pred_mask_slice, cmap='viridis')
    axes[1].set_title('Predicted Nodule', fontsize=16)
    axes[1].axis('off')

    # Plot 3: Overlay
    axes[2].imshow(scan_slice, cmap='gray')
    axes[2].imshow(pred_mask_slice, cmap='Reds', alpha=0.5)
    axes[2].set_title('Nodule Overlay', fontsize=16)
    axes[2].axis('off')

    plt.tight_layout()
    plt.show()

